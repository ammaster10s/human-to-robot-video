"""Run every demo once and collect a small, shareable results folder.

Runs the grip comparison, the verification controls, the demonstrator feedback
examples and the policy baseline, then writes `results/summary.md` plus the
JSON reports and preview GIFs it is based on. Full outputs stay under `--out`.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

from feedback import example_takes, review
from verify_controls import run_controls

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent


def _cli(script: str, out: Path) -> dict:
    process = subprocess.run(
        [sys.executable, str(SCRIPTS / script), *(["--compare"] if script == "run.py" else []), "--out", str(out)],
        capture_output=True, text=True, cwd=ROOT,
    )
    if process.returncode not in (0, 2):
        raise RuntimeError(f"{script} failed: {process.stderr.strip()}")
    return json.loads(process.stdout)


def _mm(metres: float) -> str:
    return f"{metres * 1000:.2f} mm"


def summarize(grip: dict, controls: dict, feedback: dict, policy: dict) -> str:
    lines = [
        "# Demo results",
        "",
        "Generated by `python scripts/demo.py` on the built-in synthetic demonstration in MuJoCo",
        "(one simulated gantry and a rigid block). The numbers show that the pipeline",
        "runs end to end; they are not evidence of transfer to real footage or hardware.",
        "",
        "## 1. Language-selected grip force",
        "",
        "| Instruction | Target per jaw | Measured mean carry force | Placement error | Accepted |",
        "|---|---|---|---|---|",
    ]
    for mode, trial in grip["trials"].items():
        physical = trial["physical"]
        lines.append(
            f"| `grip {'gently' if mode == 'gentle' else 'firmly'}` | {trial['grip_target_n']:.1f} N "
            f"| {physical['mean_carry_force_n']:.2f} N | {_mm(physical['placement_error_m'])} "
            f"| {'yes' if trial['accepted'] else 'no'} |"
        )
    lines += [
        "",
        "Replays: `gentle.gif`, `firm.gif`.",
        "",
        "## 2. Verification negative controls",
        "",
        "| Candidate | Expected | Decision | Why |",
        "|---|---|---|---|",
    ]
    for name, result in controls["controls"].items():
        why = "; ".join(result["visual_issues"] + result["physical_reasons"]) or "all checks passed"
        lines.append(f"| `{name}` | {result['expected']} | {result['decision']} | {why} |")
    lines += [
        "",
        "## 3. Feedback to the demonstrator",
        "",
        "| Recorded take | Usable | Problem | Instruction shown to the demonstrator |",
        "|---|---|---|---|",
    ]
    for name, result in feedback.items():
        first = result["feedback"][0]
        lines.append(f"| `{name}` | {'yes' if result['usable'] else 'no'} | {first['problem'] or '—'} "
                     f"| {first['instruction']} |")
    lines += [
        "",
        "## 4. Trajectory-template policy baseline",
        "",
        "| Layouts | Successful | Mean goal error |",
        "|---|---|---|",
    ]
    for split in ("seen", "held_out"):
        result = policy[split]
        lines.append(f"| {split.replace('_', '-')} | {result['successful']} / {result['trials']} "
                     f"| {_mm(result['mean_goal_error_m'])} |")
    lines += [
        "",
        "The baseline averages progress along a straight start-to-goal path, and the held-out",
        "layouts are also straight moves, so this checks consistency rather than generalization.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "runs" / "demo", help="new directory for full outputs")
    parser.add_argument("--results", type=Path, default=ROOT / "results", help="summary folder (overwritten)")
    args = parser.parse_args()
    try:
        args.out.mkdir(parents=True)
        comparison = _cli("run.py", args.out / "compare")
        grip = {"comparison": comparison, "trials": {
            mode: json.loads((args.out / "compare" / mode / "report.json").read_text(encoding="utf-8"))
            for mode in ("gentle", "firm")
        }}
        controls = run_controls(args.out / "controls")
        feedback = {name: review(frames) for name, frames in example_takes().items()}
        policy = _cli("policy.py", args.out / "policy")

        args.results.mkdir(parents=True, exist_ok=True)
        for mode in ("gentle", "firm"):
            shutil.copyfile(args.out / "compare" / mode / "video" / "preview.gif", args.results / f"{mode}.gif")
        reports = {"grip_comparison.json": grip, "verification_controls.json": controls,
                   "demonstrator_feedback.json": feedback, "policy_baseline.json": policy}
        for name, value in reports.items():
            (args.results / name).write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
        (args.results / "summary.md").write_text(summarize(grip, controls, feedback, policy), encoding="utf-8")
    except (OSError, ValueError, RuntimeError) as error:
        parser.exit(1, f"{parser.prog}: {error}\n")

    ok = (comparison["accepted"] and controls["all_as_expected"]
          and feedback["good"]["usable"] and not any(r["usable"] for n, r in feedback.items() if n != "good")
          and policy["held_out"]["successful"] == policy["held_out"]["trials"])
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to a legacy code page
    print((args.results / "summary.md").read_text(encoding="utf-8"))
    return 0 if ok else 2


if __name__ == "__main__":
    raise SystemExit(main())
